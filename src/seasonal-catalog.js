const effects = (s) =>
  Object.fromEntries(
    s
      .split(',')
      .filter(Boolean)
      .map((pair) => {
        const [k, n] = pair.split(':');
        return [k, Number(n)];
      }),
  );
const siteId = (s) =>
  ({ woods: 'forest', mountain: 'mountains', temple: 'ruins' })[s] || s;
const fixed = (category, rows) =>
  rows.map(([id, title, site, text, change, special = null]) => ({
    id,
    category,
    title,
    site: siteId(site),
    text,
    effects: effects(change),
    special,
  }));
