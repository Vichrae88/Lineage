export function moralChoices(key, legacyOptions) {
  const spec = dilemmas[key];
  if (!spec) return legacyOptions;
  const base = structuredClone(spec.choices);
  for (const o of legacyOptions.filter(
    (o) => !['support', 'mediate', 'refuse'].includes(o.id),
  )) {
    const values = extraValues[o.id] || ['restraint', 'reciprocity'];
    const personal = {
      ruler: { reputation: values.includes('expedience') ? -3 : 1 },
      adviser: { loyalty: values.includes('order') ? -3 : 2 },
      sponsor: { trust: -3 },
    };
    // No price buys away the personal cost of authority or the use of private lives.
    let risk = null;
    if (['quarantine', 'mobile-care', 'local-healers'].includes(o.id))
      risk = harm('epidemic', o.id === 'quarantine' ? 0.15 : 0.27, 'affected');
    if (['bounty', 'dismantle', 'sanctuary', 'lure', 'keepers'].includes(o.id))
      risk = harm(
        o.id === 'bounty'
          ? 'rescue'
          : o.id === 'sanctuary'
            ? 'predator'
            : 'ward',
        0.25,
      );
    if (['bond', 'work-credit', 'lease-tools', 'public-meadow'].includes(o.id))
      risk = harm('work', 0.19);
    if (['escort', 'quiet-exile', 'witness', 'temporary-ferry'].includes(o.id))
      risk = harm('passage', 0.22, 'affected');
    const pledge = [
      'amnesty',
      'delegates',
      'retirement',
      'memorial',
      'seed-bank',
    ].includes(o.id)
      ? duty('Revisit ' + o.label.toLowerCase())
      : null;
    base.push({
      ...structuredClone(o),
      stakes: { values, personal, risk, pledge, conditions: [] },
    });
  }
  return base;
}
