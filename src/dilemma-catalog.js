// No moral score: these are competing commitments, not a good/bad ladder.
const choice = (
  id,
  label,
  note,
  cost,
  effects,
  relations,
  values,
  personal = {},
  risk = null,
  pledge = null,
  conditions = [],
) => ({
  id,
  label,
  note,
  cost,
  effects,
  relations,
  stakes: { values, personal, risk, pledge, conditions },
});
const harm = (kind, chance, actor = 'adviser') => ({ kind, chance, actor });
const duty = (title) => ({ title, deadline: 4 });
const follow = (
  id,
  label,
  note,
  cost,
  effects,
  relations,
  values,
  personal = {},
  honor = true,
) => ({
  ...choice(id, label, note, cost, effects, relations, values, personal),
  honor,
});
const issue = (question, choices, aftermath) => {
  if (!aftermath.some((o) => o.cost === 0))
    aftermath.reduce((a, b) => (a.cost < b.cost ? a : b)).cost = 0;
  return { question, choices, aftermath };
};
