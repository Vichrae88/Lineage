export function issueChoices(e, options) {
  const key = e.archetype;
  const extra = alternatives[key];
  if (!extra || e.type === 'followup') return options;
  const available = [...options];
  for (const o of [extra, second[key]].filter(Boolean))
    if (!available.some((x) => x.id === o.id))
      available.push(structuredClone(o));
  return available;
}
